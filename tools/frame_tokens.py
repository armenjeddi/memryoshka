"""Per-token inputs of the writer's decision for a few frames, for the "one price per bit" figure.

For each chosen frame t, frames t-8 .. t are written into a memory too large to fill (price stays 0), so frame t keeps all
of its tokens at the full 4,096-bit code with the importance byte and novelty byte the real writer computes (novelty uses
the previous 8 frames; importance uses the frame alone). The page then applies the paper's rule at any price:
    value of a token at prefix length r = importance x novelty x (e(r) - 0.5) - price x (r + 24)
    a frame stays only if its kept tokens' total value exceeds price x 4,152 (its header).
The script also checks that this rule, applied at the final price of the real 7.2 MB run, gives exactly the frame's
stored code lengths in the paper's end-of-video memory.

usage: python tools/frame_tokens.py <video_id> <replay .json> <video.mp4> <frame,frame,...>
writes assets/data/frames.js and assets/img/frame_<t>.jpg
"""
import json, os, subprocess, sys
from pathlib import Path
os.environ.setdefault("MH_PREFIX_SET", "pow2")
sys.path.insert(0, "/project/6101803/armen/research_projects/memryoshka_tuning/harness")
import torch
import mh, replay
from memryoshka import memory as m
from memryoshka.memory import MemoryStore

ROOT = Path(__file__).resolve().parent.parent
vid, replay_json, video, frames = sys.argv[1], sys.argv[2], sys.argv[3], [int(x) for x in sys.argv[4].split(",")]
codec, energies, _ = mh.load_codec(torch.device("cpu"))
d = torch.load(mh.WORK / "dump" / mh.pca_tag().replace(":", "_") / os.environ.get("MH_BENCH", "vmmelong") / f"{vid}.pt", map_location="cpu",
               weights_only=False)
off, coeffs, att, tags, ts = d["offsets"].tolist(), d["coeffs"], d["attention"], d["tags"].numpy(), d["timestamps"].tolist()
R = json.load(open(replay_json))
final = R["snapshots"][-1]
final_theta = final["price"]
final_frames = {f[0]: f for f in final["frames"]}
E = sorted((int(k), float(v)) for k, v in energies.items() if int(k) in (32, 64, 128, 256, 512, 1024, 2048, 4096))


def decide(weight, theta):
    best, gain_best = 0, 0.0
    for bits, e in E:
        g = weight * (e - m.DROP_THRESHOLD) - theta * (24 + bits)
        if g > gain_best:
            best, gain_best = bits, g
    return best, gain_best


out = []
for t in frames:
    store = MemoryStore(10 ** 12, energies, tag_dim=mh.TAG_DIM, memory_format_version=3)
    for i in range(max(0, t - 8), t + 1):
        packed = replay.encode_from_coefficients(codec, coeffs[off[i]:off[i + 1]].float())
        store.write(i, ts[i], d["grids"][i], packed.payloads, att[off[i]:off[i + 1]].tolist(), tags[i])
    f = {x.frame_id: x for x in store.frames()}[t]
    toks = [[tk.position, round(tk.importance, 5)] for tk in f.tokens]
    grid = list(d["grids"][t])
    # check against the real end-of-video memory
    kept, surplus, hist = 0, 0.0, {}
    for pos, a in toks:
        b, g = decide(a * f.novelty, final_theta)
        if b:
            kept += 1; surplus += g; hist[b] = hist.get(b, 0) + 1
    frame_kept = kept > 0 and surplus > final_theta * 8 * (mh.TAG_DIM + 7)
    real = final_frames.get(t)
    real_hist = {L: n for L, n in zip(R["lengths"], real[3]) if n} if real else None
    ok = (real is None and not frame_kept) or (real is not None and frame_kept and real_hist == hist)
    print(f"frame {t}: novelty {f.novelty:.3f}, rule at final price -> {'kept' if frame_kept else 'dropped'} {hist}; "
          f"real memory -> {real_hist}; {'MATCH' if ok else 'MISMATCH'}", flush=True)
    img = ROOT / f"assets/img/frame_{t}.jpg"
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-ss", str(ts[t]), "-i", video, "-frames:v", "1", "-vf", "scale=768:-2",
                    "-q:v", "4", str(img)], check=True)
    out.append({"t": t, "time": ts[t], "img": f"assets/img/frame_{t}.jpg", "grid": grid, "novelty": round(f.novelty, 5),
                "tokens": toks, "match_final": ok})
marks = []
for minutes in (1, 5, 15, 30):
    s = min(R["snapshots"], key=lambda s: abs(s["time"] - (60 * minutes - 1)))
    marks.append({"label": f"after {minutes} min", "theta": s["price"]})
marks.append({"label": f"end ({round(R['n_frames'] / 60)} min)", "theta": final_theta})
data = {"video_id": vid, "e0": m.DROP_THRESHOLD, "token_meta_bits": 24, "frame_header_bits": 8 * (mh.TAG_DIM + 7),
        "lengths": [b for b, _ in E], "energies": [round(e, 4) for _, e in E], "marks": marks, "frames": out}
(ROOT / "assets/data/frames.js").write_text("// Generated by tools/frame_tokens.py - do not edit by hand.\nwindow.MEM_FRAMES = "
                                           + json.dumps(data, separators=(",", ":")) + ";\n")
print("frames.js written;", "marks", [(x["label"], f"{x['theta']:.3g}") for x in marks])
