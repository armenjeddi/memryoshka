"""Build the data files the page reads (plain JavaScript files, so the page also works when opened from disk).

    python tools/build_data.py stream <adaptive replay .json> <fixed-code replay .json> <thumbnail folder> [segments.json]
        -> assets/data/stream.js and assets/img/stream_thumbs.jpg
    python tools/build_data.py code <pca_basis.npz>
        -> assets/data/code.js

The replay files come from tools/replay_log.py (the paper's writer, re-run on one video with its state logged every
30 seconds). The thumbnail folder holds one JPEG every 10 seconds of the same video, named t_0001.jpg, t_0002.jpg, ...
(ffmpeg -i video.mp4 -vf "fps=1/10,scale=160:-2" t_%04d.jpg).
"""
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BIN = 3            # seconds of video per chart column in the data (the chart re-bins to its pixel width)
THUMB_W, THUMB_H, THUMB_COLS = 128, 72, 20
TOKEN_BYTES_16BIT = 3584 * 2     # one Qwen2.5-VL-7B visual token at 16 bits


def bins_for(snapshot, n_seen):
    """Per BIN-second column: tokens kept per second of video, mean code length of the kept tokens, frames kept."""
    nb = math.ceil(n_seen / BIN)
    tok, bits, kept = [0] * nb, [0] * nb, [0] * nb
    wsum = [0] * nb
    for fid, ntok, mean_bits, _hist in snapshot["frames"]:
        b = fid // BIN
        tok[b] += ntok
        kept[b] += 1
        bits[b] += mean_bits * ntok
        wsum[b] += ntok
    width = [min(BIN, n_seen - b * BIN) for b in range(nb)]
    return ([round(tok[b] / width[b]) for b in range(nb)],
            [round(bits[b] / wsum[b]) if wsum[b] else 0 for b in range(nb)],
            kept)


def stream(adaptive_path, fixed_path, thumb_dir, segments_path=None):
    out = {"bin_s": BIN, "variants": {}}
    for name, path in (("adaptive", adaptive_path), ("fixed4096", fixed_path)):
        d = json.load(open(path))
        snaps = []
        for s in d["snapshots"]:
            tok, bits, kept = bins_for(s, s["frame"])
            row = {"t": s["frame"], "kept": s["frames_kept"], "tokens": s["tokens_kept"], "bytes": s["bytes"],
                   "hist": s["hist"], "tok": tok, "kept_n": kept}
            if name == "adaptive":
                row["bits"] = bits
            snaps.append(row)
        out["variants"][name] = {"snapshots": snaps, "final_sha16": d["final_sha16"]}
        out.update(video_id=d["video_id"], n_frames=d["n_frames"], budget_bytes=d["budget"], every_s=d["every"],
                   lengths=d["lengths"], energies={str(k): round(v, 4) for k, v in d["energies"].items()})
    tokens_per_frame = max(f[1] for f in json.load(open(adaptive_path))["snapshots"][0]["frames"])
    out["tokens_per_frame"] = tokens_per_frame
    out["full_precision_frames"] = out["budget_bytes"] / (tokens_per_frame * TOKEN_BYTES_16BIT)
    # thumbnail sprite
    from PIL import Image
    files = sorted(Path(thumb_dir).glob("t_*.jpg"))
    rows = math.ceil(len(files) / THUMB_COLS)
    sheet = Image.new("RGB", (THUMB_COLS * THUMB_W, rows * THUMB_H), (0, 0, 0))
    for i, f in enumerate(files):
        im = Image.open(f).convert("RGB").resize((THUMB_W, THUMB_H), Image.LANCZOS)
        sheet.paste(im, ((i % THUMB_COLS) * THUMB_W, (i // THUMB_COLS) * THUMB_H))
    sheet.save(ROOT / "assets/img/stream_thumbs.jpg", quality=74, optimize=True, progressive=True)
    out["thumbs"] = {"src": "assets/img/stream_thumbs.jpg", "every_s": 10, "count": len(files), "w": THUMB_W,
                     "h": THUMB_H, "cols": THUMB_COLS}
    if segments_path:  # named parts of the stream, e.g. [["Sintel", 597, 1485], ...] in seconds
        out["segments"] = json.load(open(segments_path))
    text = "// Generated by tools/build_data.py stream - do not edit by hand.\nwindow.MEM_STREAM = " + \
           json.dumps(out, separators=(",", ":")) + ";\n"
    (ROOT / "assets/data/stream.js").write_text(text)
    print("stream.js", len(text) // 1024, "KB;", "thumbs", len(files))


def code(npz_path):
    import numpy as np
    z = np.load(npz_path)
    s2 = z["sigma"].astype(np.float64) ** 2
    out = {"dims": int(z["components"].shape[0]), "components": int(s2.size), "planes": int(z["plane_gains"].size),
           "sigma2": [float(f"{v:.5g}") for v in (s2 / s2.sum()).tolist()],
           "gains": [float(f"{v:.5g}") for v in z["plane_gains"].tolist()],
           "order": z["bit_order"].astype(int).reshape(-1).tolist()}
    text = "// Generated by tools/build_data.py code - do not edit by hand.\n" \
           "// sigma2: share of PCA variance per component; gains: share of a unit Gaussian's variance removed by\n" \
           "// each bit plane; order: (component, plane) pairs in the order the nested code stores them.\n" \
           "window.MEM_CODE = " + json.dumps(out, separators=(",", ":")) + ";\n"
    (ROOT / "assets/data/code.js").write_text(text)
    print("code.js", len(text) // 1024, "KB")


if __name__ == "__main__":
    if sys.argv[1] == "stream":
        stream(*sys.argv[2:6])
    elif sys.argv[1] == "code":
        code(sys.argv[2])
    else:
        sys.exit(__doc__)
